// Precompile the two MIDL JSON schemas into a STANDALONE ESM validator module
// (no runtime `new Function` / eval). This keeps the front-shell working under a
// strict Content-Security-Policy that forbids 'unsafe-eval'. Run at build time;
// the output (src/generated/midl-validators.mjs) is committed and imported by
// validate.ts. Re-run whenever the schemas change (wired into `npm run build`).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import _Ajv2020 from "ajv/dist/2020.js";
import _standaloneCode from "ajv/dist/standalone/index.js";

// ajv ships CommonJS; normalise the default export under ESM interop.
const Ajv2020 = _Ajv2020.default ?? _Ajv2020;
const standaloneCode = _standaloneCode.default ?? _standaloneCode;

const here = path.dirname(fileURLToPath(import.meta.url));
const schemasDir = path.resolve(here, "../../schemas");
const outDir = path.resolve(here, "../src/generated");
// CommonJS output (.cjs): Ajv standalone emits `require(...)` for its runtime
// helpers. Emitting ESM (.mjs) mixes `export` with `require`, which node's
// strict ESM loader (used by vitest) rejects. A .cjs module is loaded as
// CommonJS everywhere (vitest/node) and bundled cleanly by vite/tsup/esbuild.
const outFile = path.join(outDir, "midl-validators.cjs");

const configSchema = JSON.parse(readFileSync(path.join(schemasDir, "yb-midl-config.schema.json"), "utf8"));
const capsSchema = JSON.parse(readFileSync(path.join(schemasDir, "yb-midl-capabilities.schema.json"), "utf8"));

// Same options validate.ts used at runtime, plus code.source/esm so Ajv emits a
// standalone module instead of eval-compiling. Reference each schema by an
// explicit key so the generated module exports match validate.ts's imports.
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  code: { source: true }, // CJS output — see outFile note above
});
ajv.addSchema(configSchema, "config");
ajv.addSchema(capsSchema, "caps");

let moduleCode = standaloneCode(ajv, {
  validateConfig: "config",
  validateCaps: "caps",
});

// Ajv standalone emits `require("ajv/dist/runtime/ucs2length")` for unicode
// string-length checks. Inline it so the module has ZERO external requires and
// is fully self-contained — it then loads identically under vite (bundled),
// vitest (from the vendored submodule with no node_modules), and node. Guard
// against any OTHER runtime require silently slipping in.
const runtimeReqs = [...moduleCode.matchAll(/require\("(ajv\/dist\/runtime\/[^"]+)"\)/g)].map((m) => m[1]);
const unhandled = [...new Set(runtimeReqs)].filter((r) => r !== "ajv/dist/runtime/ucs2length");
if (unhandled.length) {
  throw new Error(`gen-validators: unhandled ajv runtime require(s): ${unhandled.join(", ")} — add an inline.`);
}
// UCS-2 code-unit length (JSON Schema string length semantics). Stable algorithm.
const UCS2LENGTH =
  "function ucs2length(str){const len=str.length;let length=0,pos=0,value;" +
  "while(pos<len){length++;value=str.charCodeAt(pos++);" +
  "if(value>=0xd800&&value<=0xdbff&&pos<len){value=str.charCodeAt(pos);" +
  "if((value&0xfc00)===0xdc00)pos++;}}return length;}\n";
moduleCode = UCS2LENGTH + moduleCode.replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, "ucs2length");

const header =
  "// @generated by ts/scripts/gen-validators.mjs — DO NOT EDIT.\n" +
  "// CSP-safe standalone MIDL validators (no runtime eval). Regenerate via `npm run gen:validators`.\n" +
  "/* eslint-disable */\n";

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, header + moduleCode, "utf8");

// Type declaration so validate.ts (TS) can import the generated .cjs. The
// standalone validators are Ajv ValidateFunctions (callable + `.errors`).
const dts =
  "// @generated by ts/scripts/gen-validators.mjs — DO NOT EDIT.\n" +
  'import type { ValidateFunction } from "ajv";\n' +
  "export const validateConfig: ValidateFunction;\n" +
  "export const validateCaps: ValidateFunction;\n";
writeFileSync(path.join(outDir, "midl-validators.d.cts"), dts, "utf8");

console.log(`[gen-validators] wrote ${path.relative(process.cwd(), outFile)} (${moduleCode.length} bytes) + .d.cts`);
