// Build the device-hosted MIDL editor for embedding in the display firmware.
//
//   node scripts/build-device.mjs          build + write device/dist/
//   node scripts/build-device.mjs --check  build in memory; fail when over the
//                                          size budget or when the committed
//                                          device/dist/ is stale
//
// Output (committed, so the firmware build needs no Node):
//   device/dist/index.html.gz   the whole page, JS + CSS inlined, gzip -9
//   device/dist/manifest.json   files, sizes, sha256 (raw and gzipped)
//
// Freshness is judged on the sha256 of the UNCOMPRESSED page: gzip bytes can
// differ between zlib builds (Node versions) for the same input.
import { build } from "vite";
import { gzipSync, constants } from "node:zlib";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const BUDGET_GZ_BYTES = 220 * 1024;
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const outDir = path.join(root, "device", "dist");
const check = process.argv.includes("--check");

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

await build({ configFile: path.join(root, "vite.device.config.ts"), root });

let js = readFileSync(path.join(root, "dist-device-build", "device-editor.js"), "utf8");
const css = readFileSync(path.join(root, "device", "device.css"), "utf8");
const tpl = readFileSync(path.join(root, "device", "index.html"), "utf8");

// An inline <script> ends at the first "</script"; escape any occurrence in
// strings/regexes of the bundle ("<\/script" is the same string in JS).
js = js.replace(/<\/(script)/gi, "<\\/$1");
if (!tpl.includes("/*__DEVICE_JS__*/") || !tpl.includes("/*__DEVICE_CSS__*/")) {
  throw new Error("device/index.html lost its /*__DEVICE_JS__*/ or /*__DEVICE_CSS__*/ placeholder");
}
const html = tpl
  .replace("/*__DEVICE_CSS__*/", () => css.replace(/<\/(style)/gi, "<\\/$1").trim())
  .replace("/*__DEVICE_JS__*/", () => js.trim());

const raw = Buffer.from(html, "utf8");
const gz = gzipSync(raw, { level: constants.Z_BEST_COMPRESSION });

const files = [
  {
    path: "index.html.gz",
    servePath: "/editor",
    contentType: "text/html; charset=utf-8",
    contentEncoding: "gzip",
    bytes: raw.length,
    gzBytes: gz.length,
    sha256: sha256(raw),
    gzSha256: sha256(gz),
  },
];
const totalGzBytes = files.reduce((n, f) => n + f.gzBytes, 0);
const manifest = {
  name: "midl-device-editor",
  version: JSON.parse(readFileSync(path.join(root, "package.json"), "utf8")).version,
  note: "Generated by editor/scripts/build-device.mjs; embedded by the display firmware from the midl submodule.",
  budgetGzBytes: BUDGET_GZ_BYTES,
  totalGzBytes,
  files,
};

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
for (const f of files) console.log(`${f.path}: ${kb(f.bytes)} raw, ${kb(f.gzBytes)} gz`);
console.log(`total ${kb(totalGzBytes)} gz (budget ${kb(BUDGET_GZ_BYTES)})`);

let failed = false;
if (totalGzBytes > BUDGET_GZ_BYTES) {
  console.error(`error: device editor is ${kb(totalGzBytes)} gzipped, over the ${kb(BUDGET_GZ_BYTES)} budget`);
  failed = true;
}

if (check) {
  const mPath = path.join(outDir, "manifest.json");
  const committed = existsSync(mPath) ? JSON.parse(readFileSync(mPath, "utf8")) : null;
  const stale = !committed ||
    committed.files.length !== files.length ||
    files.some((f, i) => committed.files[i].path !== f.path || committed.files[i].sha256 !== f.sha256);
  if (stale) {
    console.error("error: editor/device/dist is stale: run `npm run build:device -w @yey-boats/midl-editor` and commit it");
    failed = true;
  } else {
    // The committed gzip must decompress to the same page.
    const cgz = readFileSync(path.join(outDir, "index.html.gz"));
    if (sha256(cgz) !== committed.files[0].gzSha256) {
      console.error("error: device/dist/index.html.gz does not match its manifest gzSha256");
      failed = true;
    }
  }
} else if (!failed) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(path.join(outDir, "index.html.gz"), gz);
  writeFileSync(path.join(outDir, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  console.log(`wrote ${path.relative(process.cwd(), outDir)}/`);
}
process.exit(failed ? 1 : 0);
